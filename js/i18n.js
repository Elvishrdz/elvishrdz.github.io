const I18N_STORAGE_KEY = "preferred-lang";

/* Initial language: saved preference > browser language > English (default).
   A Spanish browser still loads in Spanish; everything else defaults to English. */
function getInitialLang() {
  const saved = localStorage.getItem(I18N_STORAGE_KEY);
  if (saved && I18N[saved]) return saved;
  const browser = (navigator.language || "en").slice(0, 2).toLowerCase();
  return I18N[browser] ? browser : "en";
}

let currentLang = getInitialLang();

/* Aplica las traducciones a todo el DOM */
function applyLang(lang) {
  const dict = I18N[lang];
  if (!dict) return;
  currentLang = lang;

  document.documentElement.lang = dict.htmlLang;
  document.title = dict.metaTitle;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", dict.metaDesc);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key] != null) el.innerHTML = dict[key];
  });

  // El footer contiene el año dentro de un span; lo re-poblamos tras traducir.
  const yearEl = document.getElementById("year");
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  // Estado visual del selector
  document.querySelectorAll(".lang-switch__btn").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
  const switchEl = document.getElementById("langSwitch");
  if (switchEl) switchEl.dataset.active = lang;

  localStorage.setItem(I18N_STORAGE_KEY, lang);

  // Avisar a main.js para reiniciar el typewriter en el nuevo idioma
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

/* Texto/array de frases del typewriter para el idioma actual */
function getTypewriterPhrases() {
  return I18N[currentLang].typewriter;
}

/* Conectar los botones del selector */
document.querySelectorAll(".lang-switch__btn").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

/* Aplicar el idioma inicial al cargar */
applyLang(currentLang);
